import { describe, it, expect } from 'vitest';
import { noteIsInNotebook, receiveNotebookId } from '../lib/notebookId';

/**
 * Notebook membership rides inside the encrypted note payload, so a note
 * shared with us arrives carrying the SENDER's notebook id — generated by
 * their client as a local `crypto.randomUUID()` and meaningless here.
 *
 * Two things have to hold at once, and they pull in opposite directions:
 *   1. we must not hold it as if it were ours (it is a correlator, and a
 *      future filter change could misuse it);
 *   2. we must not lose it, because a recipient's edit re-encrypts the WHOLE
 *      content blob — writing null would delete the OWNER's notebook
 *      assignment the moment the recipient touches the note.
 */
describe('receiveNotebookId', () => {
  it('keeps our own notebook id usable', () => {
    expect(receiveNotebookId('nb-1', false)).toEqual({ notebookId: 'nb-1' });
  });

  it('does not surface a sender notebook id as ours', () => {
    expect(receiveNotebookId('owner-nb', true).notebookId).toBeNull();
  });

  /** The half that prevents data loss for the owner. */
  it('preserves the sender notebook id for write-back', () => {
    expect(receiveNotebookId('owner-nb', true).ownerNotebookId).toBe('owner-nb');
  });

  it('never sets ownerNotebookId on a note we own', () => {
    expect(receiveNotebookId('nb-1', false).ownerNotebookId).toBeUndefined();
  });

  it('normalises absent, null and empty to null', () => {
    for (const v of [undefined, null, '']) {
      expect(receiveNotebookId(v, false).notebookId).toBeNull();
      expect(receiveNotebookId(v, true).notebookId).toBeNull();
      expect(receiveNotebookId(v, true).ownerNotebookId).toBeNull();
    }
  });

  /** A non-string from a hostile or newer payload must not become an id. */
  it('ignores a non-string value', () => {
    expect(receiveNotebookId(42, false).notebookId).toBeNull();
    expect(receiveNotebookId({ id: 'x' }, true).ownerNotebookId).toBeNull();
  });
});

describe('which notebook a note belongs to', () => {
  /**
   * The owner's copy carries notebookId; the RECIPIENT's copy of the same note
   * carries ownerNotebookId, because the id names a notebook in the sender's
   * account. Matching only the first would make an accepted shared notebook
   * open empty.
   */
  it('matches a note in one of our own notebooks', () => {
    expect(noteIsInNotebook({ notebookId: 'nb1' }, 'nb1')).toBe(true);
  });

  it('matches a received note against the sender notebook', () => {
    expect(noteIsInNotebook({ notebookId: null, ownerNotebookId: 'nb1' }, 'nb1')).toBe(true);
  });

  it('does not match a different notebook', () => {
    expect(noteIsInNotebook({ notebookId: 'nb1' }, 'nb2')).toBe(false);
    expect(noteIsInNotebook({ ownerNotebookId: 'nb1' }, 'nb2')).toBe(false);
  });

  it('does not match a note in no notebook at all', () => {
    expect(noteIsInNotebook({ notebookId: null, ownerNotebookId: null }, 'nb1')).toBe(false);
    expect(noteIsInNotebook({}, 'nb1')).toBe(false);
  });

  /** The two fields together are what a received note round-trips. */
  it('agrees with what receiveNotebookId produces for a share', () => {
    const received = receiveNotebookId('nb1', true);
    expect(noteIsInNotebook(received, 'nb1')).toBe(true);
  });
});
